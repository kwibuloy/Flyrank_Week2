-- Creates the tasks table and the three example tasks.
-- Postgres runs this automatically the first time its data volume is empty
-- (it is mounted into /docker-entrypoint-initdb.d). It is also safe to run again by hand.

CREATE TABLE IF NOT EXISTS tasks (
    id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT    NOT NULL,
    done  BOOLEAN NOT NULL DEFAULT FALSE
);

INSERT INTO tasks (title, done)
SELECT title, done
FROM (VALUES ('Workout', FALSE), ('Eat', TRUE), ('Shower', TRUE)) AS example(title, done)
WHERE NOT EXISTS (SELECT 1 FROM tasks);
